def core_policy(layer: str) -> dict:
    if layer not in {"L1", "L2"}:
        raise ValueError("unsupported core layer")
    catalog = []
    for (
        output,
        inputs,
        quantities,
        fact_group,
        materialized,
        passthrough,
        minimum,
        discrete,
    ) in _CATALOG[layer]:
        catalog.append(
            {
                "output": output,
                "required_inputs": list(inputs),
                "quantity_requirements": list(quantities),
                "required_source_facts": list(_FACT_GROUPS[fact_group]),
                "materialized": materialized,
                "passthrough": passthrough,
                "admission_minimum": minimum,
                "basis": "observed_numeric_quantity.v1"
                if quantities
                else "observed_price_sequence.v1",
                "discrete_values": list(discrete) if discrete is not None else None,
            }
        )
    return {
        "version": "native_observed_core_" + layer.lower() + ".v1",
        "profile_version": "native_core_" + layer.lower() + ".v1",
        "layer": layer,
        "input_mode": "native_observation_research.v1",
        "source_basis": "observed_price_and_numeric_quantity_sequence.v1",
        "origin_profile": "core_v1",
        "origin_profile_sha256": _ORIGIN[layer],
        "resolved_profile_sha256": _RESOLVED[layer],
        "parent_layer": "L0" if layer == "L1" else "L1",
        "parent_table": "research_bar_views" if layer == "L1" else "research_indicator_frames",
        "table": "research_indicator_frames"
        if layer == "L1"
        else "research_derived_indicator_frames",
        "limits": {"sequences": 8, "rows": 20000, "files": 128, "physical_bytes": 67108864},
        "history_policy": "configured_atomic_group_admission_no_warmup_mask.v1",
        "spec_admission": [
            {"spec_id": name, "observed_call_safe": safe, "configured_group_minimum": minimum}
            for name, safe, minimum in _SPEC_ADMISSION
        ]
        if layer == "L1"
        else [],
        "catalog": catalog,
        "runtime_profile": {
            "pandas_ta_classic": "0.4.47",
            "talib_absent": True,
            "numba": "0.65.1",
            "scipy": "1.17.1",
            "ta_source_sha256": "1558b2d9c8b0056ac26610101a554018d6fe3ee5e747d0610e5347efa1628837",
        },
        "quantity_basis": "observed_numeric_quantity.v1_no_units_inferred",
        "execution_eligible": False,
    }


def core_policy_ref(layer: str) -> dict:
    policy = core_policy(layer)
    return {key: policy[key] for key in ["version", "profile_version", "table", "parent_table"]}
